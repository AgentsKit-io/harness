#!/usr/bin/env node
/**
 * The CLI reference, walked from the commander tree itself.
 *
 * Parsing `--help` output would document the formatter, not the program: a renamed flag or a dropped option
 * would keep rendering until someone noticed. `src/cli.ts` exports `cliProgram` and skips `parseAsync` under
 * `AK_HARNESS_CLI_INTROSPECT=1`, which is all the seam this needs.
 */
import { writeFileSync, readFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { pathToFileURL } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const target = join(root, 'apps/docs/content/docs/reference/cli.mdx')

process.env['AK_HARNESS_CLI_INTROSPECT'] = '1'
const { cliProgram } = await import(pathToFileURL(join(root, 'dist/cli.js')).href)
if (!cliProgram) { console.error('dist/cli.js does not export cliProgram — run `pnpm build` first.'); process.exit(1) }

// MDX reads `<decision>` as a JSX tag and fails the build; angle brackets only survive escaped.
const escape = (text) => String(text ?? '').replace(/\|/g, '\\|').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\s*\n\s*/g, ' ').trim()

const optionRows = (command) => command.options
  .filter((option) => !option.hidden)
  .map((option) => `| \`${escape(option.flags)}\` | ${escape(option.description)} | ${option.defaultValue === undefined ? '' : `\`${JSON.stringify(option.defaultValue)}\``} |`)

const section = (command, trail, level) => {
  const path = [...trail, command.name()].filter(Boolean)
  const full = path.join(' ')
  const lines = [
    `${'#'.repeat(level)} \`${full}\``,
    '',
    command.description() ? escape(command.description()) : '',
    '',
    '```bash',
    `${full} ${command.usage() ?? ''}`.trim(),
    '```',
    '',
  ]
  if (command.options.filter((option) => !option.hidden).length) {
    lines.push('| Flag | What it does | Default |', '|---|---|---|', ...optionRows(command), '')
  }
  return lines.join('\n')
}

/** A group renders its own heading once, then one section per subcommand — no command documented twice. */
const descendants = (command, trail) => {
  const path = [...trail, command.name()].filter(Boolean)
  return command.commands.filter((child) => !child._hidden).flatMap((child) => [section(child, path, 3), ...descendants(child, path)])
}

const groups = cliProgram.commands.filter((command) => !command._hidden)
const body = groups.map((group) => {
  const children = descendants(group, ['ak-harness'])
  return children.length
    ? [section(group, ['ak-harness'], 2), ...children].join('\n')
    : section(group, ['ak-harness'], 2)
}).join('\n')

const mdx = `---
title: CLI
description: Every command, subcommand and flag of ak-harness, walked from the program itself.
---

{/* Generated by \`pnpm docs:generate\`. Do not edit by hand: edit \`src/cli.ts\` and regenerate. */}

\`ak-harness\` is the harness; \`ak-verify\` is an alias of the same binary for the common verification protocol.
Every loop command takes \`-f <path-to-loop.config.yaml>\` and defaults to \`./loop.config.yaml\`.

${body}`

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : ''
  if (current !== mdx) { console.error(`Stale: ${target}. Run "pnpm docs:generate".`); process.exit(1) }
} else {
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, mdx)
}

const count = (command) => 1 + command.commands.reduce((total, child) => total + count(child), 0)
console.log(JSON.stringify({ status: 'passed', criteria: ['cli-reference'], commands: groups.reduce((total, group) => total + count(group), 0) }))
