#!/usr/bin/env node
/**
 * The events reference: what the loop emits, what each event carries, and what it means.
 *
 * The names and fields come from the vocabulary itself (`LOOP_EVENT_TYPES`, `HARNESS_EVENT_TYPES`); the meaning
 * comes from the JSDoc next to each key, read with the same extractor the configuration reference uses.
 */
import { writeFileSync, readFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { jsdocKeysOfObject } from './lib/jsdoc-paths.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const target = join(root, 'apps/docs/content/docs/reference/events.mdx')

const { LOOP_EVENT_TYPES, HARNESS_EVENT_TYPES } = await import(join(root, 'dist/index.js'))
const docs = jsdocKeysOfObject(join(root, 'src/loop/event-vocabulary.ts'), 'LOOP_EVENT_TYPES')

const oneLine = (text) => text.replace(/\s*\n\s*/g, ' ').replace(/\|/g, '\\|').trim()
const groupOf = (type) => type.split('.')[0]

const groups = new Map()
for (const [type, fields] of Object.entries(LOOP_EVENT_TYPES)) {
  const group = groupOf(type)
  if (!groups.has(group)) groups.set(group, [])
  groups.get(group).push({ type, fields })
}

const undocumented = Object.keys(LOOP_EVENT_TYPES).filter((type) => !docs.has(type))

const body = [...groups.entries()].map(([group, events]) => [
  `## \`${group}.*\``,
  '',
  '| Event | Carries | What it means |',
  '|---|---|---|',
  ...events.map(({ type, fields }) => `| \`${type}\` | ${fields.map((field) => `\`${field}\``).join(', ')} | ${docs.has(type) ? oneLine(docs.get(type)) : ''} |`),
  '',
].join('\n')).join('\n')

const mdx = `---
title: Events
description: Every event the loop writes to its log and emits on its bus, with the fields it carries.
---

{/* Generated by \`pnpm docs:generate\`. Do not edit by hand: edit \`src/loop/event-vocabulary.ts\` and regenerate. */}

Every loop event is appended to \`<stateDir>/events.ndjson\` and emitted on the plugin bus, with \`at\` (ISO
timestamp) and \`type\` on top of the fields below. A plugin subscribes with
\`bus.on('<type>' | '*', listener)\`; a notification channel subscribes by listing types in
\`notifications.events\`.

The vocabulary is enforced by the compiler: \`appendLoopEvent\` accepts only these names, so an event that is not
here cannot be emitted — and a name here that nothing emits fails the test suite.

${Object.keys(LOOP_EVENT_TYPES).length} loop events${undocumented.length ? `, ${undocumented.length} of them still without a description` : ''}.

${body}
## Harness run events

A separate, older vocabulary: the run-level event log the harness keeps for a single verification run
(\`HARNESS_EVENT_TYPES\`), independent of the loop.

${HARNESS_EVENT_TYPES.map((type) => `- \`${type}\``).join('\n')}
`

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : ''
  if (current !== mdx) { console.error(`Stale: ${target}. Run "pnpm docs:generate".`); process.exit(1) }
} else {
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, mdx)
}

console.log(JSON.stringify({ status: 'passed', criteria: ['events-reference'], events: Object.keys(LOOP_EVENT_TYPES).length, undocumented: undocumented.length }))
